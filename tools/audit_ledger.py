#!/usr/bin/env python3
"""The PR #17 audit ledger: every file the pull request changes, each with
an audit disposition bound to the exact content that was examined.

WHY IT BINDS TO A BLOB. "Reviewed" means nothing unless it names what was
reviewed. A disposition records the git blob it was made against. When the
file changes, ``derive`` demotes the entry to NOT_REVIEWED, saying it went
stale, and ``check`` fails on any entry that disagrees with git. A file
nobody has examined says NOT_REVIEWED with its reason, and is never counted
as reviewed.

WHERE THE CHANGE SET COMES FROM. ``git diff --cached --name-status``
between the merge base with the default branch and the index, with rename
detection and no rename limit. It is not taken from the GitHub web diff,
which truncates. The index is what the next commit will hold, so a ledger
derived after staging describes the commit it is committed in. In a clean
checkout, such as CI's, the index is HEAD. ``crosscheck`` compares the
ledger with the pull request's file list from the GitHub API, saved to a
file, path by path and blob by blob.

WHAT IS NOT BOUND. Two kinds of file:

- files a tool regenerates on every change (DERIVED). For these the
  disposition names the generator and the check that reproduces them;
- this audit's own artefacts (AUDIT). These are written by the auditor and
  are not independently reviewed, which their status says.

Binding either kind to a blob would loop: each regeneration would make the
ledger stale, and each ledger update would make them stale. For the same
reason the ledger records no content facts (blob, size, digest) for them,
only that they changed.

    python tools/audit_ledger.py derive [--base SHA]
    python tools/audit_ledger.py set --status S --method M \
        [--finding F]... PATH...
    python tools/audit_ledger.py check
    python tools/audit_ledger.py crosscheck GITHUB_FILES.json
    python tools/audit_ledger.py summary
"""
from __future__ import annotations

import argparse
import fnmatch
import hashlib
import json
