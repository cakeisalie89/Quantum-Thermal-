def _git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True,
                          capture_output=True, text=True).stdout


def _git_bytes(*args: str) -> bytes:
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True,
                          capture_output=True).stdout


def kind_of(path: str) -> str:
    for pattern, kind in KINDS:
        if fnmatch.fnmatch(path, pattern):
            return kind
    return "configuration-or-data"            # unreachable: "*" matches


def _is_audit(path: str) -> bool:
    return any(fnmatch.fnmatch(path, p) for p in AUDIT_PATHS)


def _blobs(commit: str | None) -> dict:
    """path -> (mode, sha): of a commit's tree, or of the index."""
    out: dict = {}
    if commit is None:
        for line in _git("ls-files", "-s", "-z").split("\0"):
            if line:
                meta, path = line.split("\t", 1)
                mode, sha, _stage = meta.split()
                out[path] = (mode, sha)
        return out
    for line in _git("ls-tree", "-r", "-z", commit).split("\0"):
        if line:
            meta, path = line.split("\t", 1)
            mode, _typ, sha = meta.split()
            out[path] = (mode, sha)
    return out


def _volatile(path: str) -> bool:
    return _is_audit(path) or path in DERIVED


def changes(base: str, head: str | None = None) -> list:
    """Every changed path as one entry's facts, from git alone: against
    ``head``, or against the index when it is None."""
    rng = ["--cached", base] if head is None else [base, head]
    raw = _git("-c", "diff.renameLimit=0", "diff", "-M", "-z",
               "--name-status", *rng).split("\0")
    numstat = _git("-c", "diff.renameLimit=0", "diff", "-M", "-z",
                   "--numstat", *rng)
    binary = set()
    for rec in numstat.split("\0"):
        parts = rec.split("\t")
        if len(parts) == 3 and parts[0] == "-":
            binary.add(parts[2])
    old, new = _blobs(base), _blobs(head)
    out = []
    i = 0
    while i < len(raw) and raw[i]:
        status = raw[i]
        if status[0] in "RC":
            src, dst = raw[i + 1], raw[i + 2]
            i += 3
            pairs: list[tuple[str, str, str | None]] = (
                [("DELETED", src, None)] if status[0] == "R" else [])
            pairs.append(("ADDED", dst, src))
        else:
            path = raw[i + 1]
            i += 2
            change = {"A": "ADDED", "D": "DELETED", "M": "MODIFIED",
                      "T": "MODIFIED"}[status[0]]
            pairs = [(change, path, None)]
        for change, path, origin in pairs:
            before = old.get(path)
            after = new.get(path)
            side = before if change == "DELETED" else after
            if side is None:
                raise SystemExit(
                    f"git diff says {path} was {change.lower()}, and the "
                    "tree it was diffed against does not hold it there")
            facts: dict[str, object]
            if _volatile(path) and change != "DELETED":
                facts = {"new_blob": None, "size": None, "sha256": None}
            else:
                content = _git_bytes("cat-file", "blob", side[1])
                facts = {"new_blob": after[1] if after else None,
                         "size": len(content),
                         "sha256": hashlib.sha256(content).hexdigest()}
            out.append({
                "path": path, "change": change,
                "old_blob": before[1] if before else None,
                **facts, "mode": side[0],
                "binary": path in binary, "kind": kind_of(path),
                **({"renamed_from": origin} if origin else {})})
    return sorted(out, key=lambda e: e["path"])


def _current_blob(entry: dict):
    return entry["old_blob"] if entry["change"] == "DELETED" \
        else entry["new_blob"]


def load() -> dict:
    return json.loads(LEDGER.read_text(encoding="utf-8"))


def save(doc: dict) -> None:
    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    LEDGER.write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n",
                      encoding="utf-8")


def _default_disposition(e: dict) -> dict:
    if _is_audit(e["path"]):
        return {"status": "AUDIT_ARTIFACT", "reviewed_blob": None,
                "method": "written by the auditor", "findings": [],
                "note": "not independently reviewed"}
    if e["path"] in DERIVED and e["change"] != "DELETED":
        gen, chk = DERIVED[e["path"]]
        return {"status": "NOT_REVIEWED", "reviewed_blob": None,
                "method": "", "findings": [],
                "note": f"derived by {gen}; not yet reproduced with {chk}"}
    return {"status": "NOT_REVIEWED", "reviewed_blob": None, "method": "",
            "findings": [], "note": "not yet examined"}


def derive(base: str | None = None) -> dict:
    prior = load() if LEDGER.exists() else {"entries": []}
    base = base or prior.get("base") or _git(
        "merge-base", DEFAULT_BRANCH, "HEAD").strip()
    was = {e["path"]: e for e in prior["entries"]}
    entries = []
    for e in changes(base):
        d = _default_disposition(e)
        p = was.get(e["path"])
        if p is not None and p["status"] in UNBOUND and \
                p["status"] != "NOT_REVIEWED":
            if not (_is_audit(e["path"]) and p["status"] != "AUDIT_ARTIFACT"):
                d = {k: p[k] for k in ("status", "reviewed_blob", "method",
                                       "findings", "note")}
        elif p is not None and p["status"] in BOUND:
            if p["reviewed_blob"] == _current_blob(e):
                d = {k: p[k] for k in ("status", "reviewed_blob", "method",
                                       "findings", "note")}
            else:
                d = {**d, "findings": p["findings"],
                     "note": f"STALE: {p['status']} at blob "
                             f"{p['reviewed_blob']}, changed since; "
                             f"was: {p['method']}"}
        elif p is not None and p["status"] == "NOT_REVIEWED":
            d = {**d, "findings": p["findings"], "note": p["note"]}
        entries.append({**e, **d})
    doc = {"schema": SCHEMA, "base": base,
           "statuses": STATUSES,
           "derived": {k: {"generator": v[0], "check": v[1]}
                       for k, v in sorted(DERIVED.items())},
           "entries": entries}
    save(doc)
    return doc


def _finding_ids() -> set:
    if not FINDINGS.exists():
        return set()
    return {f["id"] for f in json.loads(
        FINDINGS.read_text(encoding="utf-8"))["findings"]}


def problems(doc: dict, live: list | None = None) -> list:
    """Every way the ledger disagrees with git or with its own rules."""
    out: list = []
    live = changes(doc["base"]) if live is None else live
    have = {e["path"]: e for e in doc["entries"]}
    facts = ("change", "old_blob", "new_blob", "mode", "size", "sha256",
             "binary")
    for e in live:
        got = have.pop(e["path"], None)
        if got is None:
            out.append(f"{e['path']}: changed by the PR and missing")
            continue
        for k in facts:
            if got.get(k) != e[k]:
                out.append(f"{e['path']}: {k} is {got.get(k)!r} in the "
                           f"ledger and {e[k]!r} in git; re-derive")
    out += [f"{p}: in the ledger but not changed by the PR" for p in have]
    ids = _finding_ids()
    for e in doc["entries"]:
        st = e.get("status")
        if st not in STATUSES:
            out.append(f"{e['path']}: unknown status {st!r}")
            continue
        if st in BOUND and _volatile(e["path"]):
            out.append(f"{e['path']}: {st} on a file the ledger cannot bind "
                       "to its content; it is regenerated or the audit's own")
        elif st in BOUND:
            if e.get("reviewed_blob") != _current_blob(e):
                out.append(f"{e['path']}: {st} names blob "
                           f"{e.get('reviewed_blob')}, but the file is "
                           f"{_current_blob(e)}: STALE")
            if not e.get("method"):
                out.append(f"{e['path']}: {st} says nothing of how")
        if st == "CHECKED_GENERATED" and e["path"] not in DERIVED:
            out.append(f"{e['path']}: CHECKED_GENERATED, but no generator "
                       "rewrites it; bind it to its blob instead")
        if st == "AUDIT_ARTIFACT" and not _is_audit(e["path"]):
            out.append(f"{e['path']}: AUDIT_ARTIFACT outside the audit's "
                       "own paths")
        if st == "NOT_REVIEWED" and not e.get("note"):
            out.append(f"{e['path']}: NOT_REVIEWED without a reason")
        for f in e.get("findings", []):
            if f not in ids:
                out.append(f"{e['path']}: names finding {f}, which "
                           "docs/audit/findings.json does not hold")
    return out


def set_status(paths: list, status: str, method: str, findings: list,
               note: str) -> list:
    if status not in STATUSES:
        raise SystemExit(f"unknown status {status!r}")
    if status in BOUND and any(_volatile(p) for p in paths):
        raise SystemExit(f"{status} binds to content, and these are "
                         "regenerated or the audit's own: "
                         f"{[p for p in paths if _volatile(p)]}")
    doc = load()
    by = {e["path"]: e for e in doc["entries"]}
    missing = [p for p in paths if p not in by]
    if missing:
        raise SystemExit(f"not changed by the PR: {missing}")
    for p in paths:
        e = by[p]
        e["status"] = status
        e["reviewed_blob"] = _current_blob(e) if status in BOUND else None
        e["method"] = method
        e["findings"] = sorted(set(e.get("findings", [])) | set(findings))
        e["note"] = note
    save(doc)
    return paths


def crosscheck(doc: dict, github_files: list) -> list:
    """The ledger against the pull request's file list from the API:
    the same paths, statuses and blob ids."""
    out = []
    api = {f["filename"]: f for f in github_files}
    want = {"ADDED": "added", "DELETED": "removed", "MODIFIED": "modified"}
    for e in doc["entries"]:
        f = api.pop(e["path"], None)
        if f is None:
            out.append(f"{e['path']}: not in the API's file list")
            continue
        if f["status"] != want[e["change"]]:
            out.append(f"{e['path']}: {e['change']} here, {f['status']} in "
                       "the API")
        # the API names the blob at the head, or the deleted blob; a file
        # the ledger keeps no content facts for is compared by path only
        if not (_volatile(e["path"]) and e["change"] != "DELETED") and \
                f.get("sha") not in (_current_blob(e), None):
            out.append(f"{e['path']}: blob {_current_blob(e)} here, "
                       f"{f.get('sha')} in the API")
    out += [f"{p}: in the API's list, not in the ledger" for p in api]
    return out


def summary(doc: dict) -> dict:
    by: dict = {}
    for e in doc["entries"]:
        by.setdefault(e["status"], 0)
        by[e["status"]] += 1
    kinds: dict = {}
    for e in doc["entries"]:
        k = kinds.setdefault(e["kind"], {})
        k[e["status"]] = k.get(e["status"], 0) + 1
    return {"base": doc["base"],
            "files": len(doc["entries"]), "by_status": by,
            "by_kind": kinds}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("derive")
    d.add_argument("--base")
    s = sub.add_parser("set")
    s.add_argument("--status", required=True)
    s.add_argument("--method", required=True)
    s.add_argument("--finding", action="append", default=[])
    s.add_argument("--note", default="")
    s.add_argument("paths", nargs="+")
    sub.add_parser("check")
    c = sub.add_parser("crosscheck")
    c.add_argument("github_files")
    sub.add_parser("summary")
    args = ap.parse_args(argv)
    if args.cmd == "derive":
        doc = derive(args.base)
        print(json.dumps(summary(doc)["by_status"], sort_keys=True))
        return 0
    if args.cmd == "set":
        set_status(args.paths, args.status, args.method, args.finding,
                   args.note)
        return 0
    if args.cmd == "check":
        bad = problems(load())
        for b in bad:
            print(b)
        print(f"audit ledger: {len(bad)} problem(s)")
        return 1 if bad else 0
    if args.cmd == "crosscheck":
        files = json.loads(Path(args.github_files).read_text(
            encoding="utf-8"))
        bad = crosscheck(load(), files)
        for b in bad:
            print(b)
        print(f"crosscheck against the API: {len(bad)} disagreement(s)")
        return 1 if bad else 0
    print(json.dumps(summary(load()), indent=1, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
