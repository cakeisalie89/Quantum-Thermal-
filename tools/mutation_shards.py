def specs() -> list:
    return sorted(p.name for p in MUTATIONS.glob("*.json"))


def _mutations(name: str) -> int:
    return len(json.loads((MUTATIONS / name).read_text(
        encoding="utf-8"))["mutations"])


def weights(names: list) -> dict:
    per = [WEIGHTS[n] / max(_mutations(n), 1) for n in names if n in WEIGHTS]
    rate = statistics.median(per) if per else 1.0
    return {n: WEIGHTS.get(n, _mutations(n) * rate) for n in names}


def plan(names: list | None = None, n: int = SHARDS) -> list:
    """``n`` lists of spec names; each spec in exactly one."""
    names = specs() if names is None else sorted(names)
    w = weights(names)
    shards: list[list[str]] = [[] for _ in range(n)]
    load = [0.0] * n
    for name in sorted(names, key=lambda s: (-w[s], s)):
        i = min(range(n), key=lambda k: (load[k], k))
        shards[i].append(name)
        load[i] += w[name]
    return [sorted(s) for s in shards]


def emit(shards: list | None = None) -> str:
    shards = plan() if shards is None else shards
    lines = [BEGIN]
    for i, s in enumerate(shards, 1):
        lines.append(f"          - shard: {i}")
        lines.append("            specs: >-")
        lines += [f"              tools/mutations/{name}" for name in s]
    lines.append(END)
    return "\n".join(lines)


def _job(text: str, name: str) -> str | None:
    m = re.search(rf"^  {re.escape(name)}:\s*\n(.*?)(?=^  [A-Za-z0-9_-]+:\s*$"
                  r"|\Z)", text, re.MULTILINE | re.DOTALL)
    return m.group(1) if m else None


def check_workflow(text: str | None = None) -> list:
    """Every way the workflow could run fewer specs than the plan, or report
    green without every shard passing."""
    text = WORKFLOW.read_text(encoding="utf-8") if text is None else text
    out = []
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        out.append("the generated shard block is missing or duplicated")
    else:
        block = text[text.index(BEGIN):text.index(END) + len(END)]
        if block != emit():
            out.append("the shard matrix is not what tools/mutation_shards.py "
                       "--emit generates for the specs on disk; regenerate it")
    shard = _job(text, "mutation-shards")
    if shard is None:
        out.append("no mutation-shards job")
    else:
        if BEGIN not in shard:
            out.append("the generated block is not the mutation-shards matrix")
        if not re.search(r"^\s+fail-fast:\s*false\s*$", shard, re.MULTILINE):
            out.append("mutation-shards must set fail-fast: false, or one red "
                       "shard cancels the others and their verdicts are lost")
        if "tools/mutation_shards.py --run ${{ matrix.specs }}" not in shard:
            out.append("mutation-shards does not run its shard's specs")
    agg = _job(text, "mutation-matrices")
    if agg is None:
        out.append("no mutation-matrices job aggregating the shards")
    else:
        if not re.search(r"^\s+needs:\s*\[?\s*mutation-shards\s*\]?\s*$", agg,
                         re.MULTILINE):
            out.append("mutation-matrices does not wait for mutation-shards")
        if not re.search(r"^\s+if:\s*\$\{\{\s*always\(\)\s*\}\}\s*$|"
                         r"^\s+if:\s*always\(\)\s*$", agg, re.MULTILINE):
            out.append("mutation-matrices must run always(): skipped when a "
                       "shard fails, it would report nothing rather than red")
        if "needs.mutation-shards.result" not in agg or \
                not re.search(r'"success"|\bsuccess\b', agg):
            out.append("mutation-matrices does not require every shard's "
                       "result to be success")
    return out


def _tracked_state(root: Path = ROOT) -> str:
    """Everything a shard could leave behind in the tree, as one string.

    The working-tree diff, the STAGED diff and the untracked files that are
    not ignored. The first alone missed the other two, and both have
    happened: a test that intent-adds a probe file puts it in the index, and
    a killed test leaves the probe on disk (D-2026-82).
    """
    def git(*args):
        r = subprocess.run(["git", "-C", str(root), *args],
                           capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit(f"git {args[0]} failed: {r.stderr[:200]}")
        return r.stdout
    return "\n".join((
        git("status", "--porcelain", "--untracked-files=no"),
        git("diff", "--binary"),
        git("diff", "--cached", "--binary"),
        git("ls-files", "--others", "--exclude-standard")))


def run(paths: list, runner=None) -> int:
    """Run one shard. Non-zero unless every spec's matrix exits 0 and the
    tracked tree is as it was."""
    names = [Path(p).name for p in paths]
    if not names:
        print("no specs given: an empty shard would pass having run nothing")
        return 1
    if sorted(names) not in plan():
        print(f"{sorted(names)} is not a shard of the committed plan; the "
              "workflow matrix is stale (tools/mutation_shards.py --emit)")
        return 1
    runner = runner or (lambda p: subprocess.run(
        [sys.executable, "tools/mutation_matrix.py", p], cwd=ROOT).returncode)
    before = _tracked_state()
    failed = []
    for p in paths:
        print(f"\n=== {p}", flush=True)
        rc = runner(p)
        if rc != 0:
            failed.append((p, rc))
    changed = _tracked_state() != before
    print("\n=== shard summary")
    for p in paths:
        rc = dict(failed).get(p, 0)
        print(f"  {'ok  ' if rc == 0 else 'FAIL'} {p}"
              + (f" (exit {rc})" if rc else ""))
    if changed:
        print("the tracked tree changed during this shard")
    return 1 if failed or changed else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--emit", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--run", nargs="*", metavar="SPEC")
    args = ap.parse_args(argv)
    if args.emit:
        print(emit())
        return 0
    if args.check:
        problems = check_workflow()
        for p in problems:
            print(p)
        if problems:
            return 1
        w = weights(specs())
        loads = [sum(w[s] for s in sh) / 60 for sh in plan()]
        print(f"{len(specs())} specs in {SHARDS} shards, each exactly once; "
              f"estimated minutes per shard {[round(x) for x in loads]}")
        return 0
    return run(args.run)


if __name__ == "__main__":
    sys.exit(main())
