"""Deterministic shards for the mutation matrices, and the runner for one.

WHY. The agent-substrate job ran every matrix serially in one job: 4h27m of
it at d633c77 (hosted run 36094744039), on a runner that GitHub stops at six
hours, and a runner lost at hour four took every result with it. Sharding
must not buy that time back with coverage, so what holds is stated here and
checked, not assumed:

* **Every spec, every cycle.** ``plan()`` puts every ``tools/mutations/*.json``
  in exactly one shard. There is no sampling and no rotation.
* **Deterministic.** Longest-processing-time on the committed WEIGHTS (the
  measured seconds of each spec in a hosted run), ties broken by name; a
  spec not yet measured is weighed at its mutation count times the median
  measured seconds per mutation. Same specs, same shards, on every machine.
* **The workflow's matrix is generated, not typed.** ``--emit`` prints the
  ``include:`` block; ``--check`` fails unless the block between the markers
  in agent-substrate.yml is exactly that, and unless the shard job, the
  aggregate job and its success test are all present in the shape that makes
  "overall green" mean "every shard passed". A spec left out of the block, a
  shard deleted, or ``fail-fast`` turned back on is a contract failure.
* **Each shard keeps every per-spec guarantee**, because each spec still runs
  through ``tools/mutation_matrix.py`` unchanged: baseline, null control,
  non-zero exit on a survivor, an anchor that does not match once, a timeout
  or a source not restored byte-identical. ``--run`` runs every spec it is
  given even after one fails, so one red spec does not hide another, and
  fails if the tracked tree differs afterwards -- git as the independent
  check of the harness's own re-hashing.
* **A lost runner is never a pass.** The aggregate job runs ``if: always()``
  and requires the shard job's result to be ``success``; a cancelled,
  skipped or timed-out shard is not success. Nothing here reads a shard's
  output to infer what it killed, so nothing can mistake silence for a kill.
"""
